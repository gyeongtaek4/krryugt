assert(!/\.department-overview \.department-list\s*\{[^}]*(max-height|overflow-y)/.test(css));
const positions = titles.map(title => dashboard.indexOf(title));
assert(positions.every((position, index) => position >= 0 && (!index || position > positions[index - 1])));
assert.equal((dashboard.match(/id="dashboardUsageMonth"/g) || []).length, 1);
assert.equal((dashboard.match(/id="costTrendReferenceMonth"/g) || []).length, 1);
assert.equal((dashboard.match(/id="costTrendPeriodMonths"/g) || []).length, 1);
assert(!dashboard.includes('class="panel cost-panel"'));
assert(dashboard.includes('id="dashboardUsageDaysHigh"'));
assert(dashboard.includes('id="dashboardUsageDaysLow"'));
assert(dashboard.includes('id="dashboardUsageDistanceHigh"'));
assert(dashboard.includes('id="dashboardUsageDistanceLow"'));
assert((dashboard.match(/<th>차량번호<\/th><th>팀<\/th>/g) || []).length === 4);
assert(!dashboard.includes('dashboardUsageStatus'));
assert(!dashboard.includes('확정월의 차량번호별 기록을 합산합니다.'));
assert(!dashboard.includes('차량별 서로 다른 운행 날짜 수'));
