assert.equal((dashboard.match(/<h4>상위<\/h4>/g) || []).length, 2);
assert.equal((dashboard.match(/<h4>하위<\/h4>/g) || []).length, 2);
assert(!dashboard.includes('많은 차량'));
assert(!dashboard.includes('적은 차량'));
assert(css.includes('.usage-ranking-tables > div + div'), 'upper/lower ranking separation styling is missing');
assert(!js.includes("getElementById('reportButton')"), 'removed report button still has an event handler');
assert(js.includes("getElementById('dashboardVehiclesShortcut')?.addEventListener('click', () => showView('차량 현황'"), 'vehicle dashboard shortcut is missing');
assert(js.includes("getElementById('dashboardContractAmountShortcut')?.addEventListener('click', () => showView('차량계약정보'"), 'contract amount dashboard shortcut is missing');
assert(js.includes("const month=document.getElementById('dashboardUsageMonth').value,item=drivingArchive[month];"), 'usage ranking must retain its selected month archive lookup');
